});

/**
 * Phase 13 cron intervals.
 *
 * WordPress ships only hourly/twicedaily/daily. `AIOL_Telemetry` and
 * `AIOL_Access_Gate` call `wp_schedule_event()` with intervals of their
 * own — and without this filter, that call fails silently: no error, no
 * log line, just an event that is never actually scheduled. Telemetry
 * would then sit in the buffer forever and the access-policy cache would
 * never refresh, both invisibly. Caught by tracing the cron call chain
 * end to end rather than by any test, because nothing had exercised it.
 */
add_filter('cron_schedules', static function (array $schedules): array {
    $schedules['aiol_five_minutes'] = [
        'interval' => 5 * MINUTE_IN_SECONDS,
        'display'  => __('Every 5 minutes (AI Operating Layer telemetry)', 'ai-operating-layer'),
    ];
    $schedules['aiol_fifteen_minutes'] = [
        'interval' => 15 * MINUTE_IN_SECONDS,
        'display'  => __('Every 15 minutes (AI Operating Layer access policy)', 'ai-operating-layer'),
    ];
    return $schedules;
});

/**
 * Bootstrap. Deliberately the only place that wires objects together, so the
 * classes themselves stay independently testable without WordPress.
 */
function aiol_bootstrap(): void
{
    $credentials = new AIOL_Credentials();
    $logger      = new AIOL_Logger();
    $client      = new AIOL_Client($credentials, $logger);
    $cache       = new AIOL_Cache();

    // Phase 13. Built alongside AIOL_Client above (0.9.0 → 0.13.0) but
    // never previously instantiated here — a wiring gap caught during
    // this session's forensic pass rather than at runtime, where it would
    // have surfaced as telemetry silently never leaving the site and the
    // dwell beacon endpoint 404ing on every request.
    $access_gate = new AIOL_Access_Gate($client, $logger);
    $telemetry   = new AIOL_Telemetry($client, $logger);

    (new AIOL_Hooks($client, $logger))->register();
    (new AIOL_Representations($cache))->register();
    (new AIOL_Actors())->register();
    (new AIOL_WooCommerce($client, $logger))->register();
    (new AIOL_Schema($client, $cache))->register();
    $access_gate->register();
    $telemetry->register();
    (new AIOL_Admin($client, $credentials, $cache, $logger, new AIOL_Diagnostics($cache), $access_gate, $telemetry))->register();
}
add_action('plugins_loaded', 'aiol_bootstrap');

/**
 * Activation: no schema of our own. The adapter stores nothing WordPress
 * could mistake for business truth - only its own connection settings, which
 * live in wp_options. There is deliberately no custom table.
 */
function aiol_activate(): void
{
    if (!get_option(AIOL_Credentials::OPTION_ENDPOINT)) {
        add_option(AIOL_Credentials::OPTION_ENDPOINT, '', '', false);
    }
    // Rewrite rules for /llms.txt must exist before the first request.
    (new AIOL_Representations(new AIOL_Cache()))->add_rewrite_rules();
    flush_rewrite_rules();
}
register_activation_hook(__FILE__, 'aiol_activate');

/**
 * Deactivation clears only caches. Credentials survive deactivation so a
 * merchant who toggles the plugin does not have to re-provision; uninstall
 * is where secrets are destroyed (uninstall.php).
 */
function aiol_deactivate(): void
{
    AIOL_Cache::flush_all();
    flush_rewrite_rules();
    // Leave no orphaned cron event behind.
    wp_clear_scheduled_hook(AIOL_WooCommerce::CRON_HOOK);
    wp_clear_scheduled_hook(AIOL_Telemetry::CRON_HOOK);
    wp_clear_scheduled_hook(AIOL_Access_Gate::CRON_HOOK);
}
register_deactivation_hook(__FILE__, 'aiol_deactivate');
