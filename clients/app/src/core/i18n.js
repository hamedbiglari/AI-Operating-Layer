export const LANGUAGES = Object.freeze(['en', 'fa']);
export const DIRECTION = Object.freeze({ en: 'ltr', fa: 'rtl' });

export function createI18n(lang = 'en') {
  let current = LANGUAGES.includes(lang) ? lang : 'en';
  const t = (key, args) => {
    const raw = MESSAGES[current][key] ?? MESSAGES.en[key] ?? key;
    if (!args) return raw;
    return raw.replace(/\{(\w+)\}/g, (_, k) => (k in args ? `${FSI}${fmt(args[k])}${PDI}` : `{${k}}`));
  };
  const fmt = (v) => (typeof v === 'number' ? new Intl.NumberFormat(current === 'fa' ? 'fa-IR' : 'en-US').format(v)
                                            : String(v));
  return {
    t,
    get lang() { return current; },
    get dir() { return DIRECTION[current]; },
    set(next) { if (LANGUAGES.includes(next)) current = next; return current; },
    number: (n) => fmt(n),
    dateTime: (iso) => {
      if (!iso) return '';
      const d = new Date(iso);
      if (Number.isNaN(d.getTime())) return '';
      return new Intl.DateTimeFormat(current === 'fa' ? 'fa-IR' : 'en-US',
                                     { dateStyle: 'medium', timeStyle: 'short' }).format(d);
    },
  };
}
