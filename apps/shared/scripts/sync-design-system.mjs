// Copies the canonical design system and icon registry into the client (ADR-137).
// Same rule as scripts/sync-design-system.php for the plugin: the copies are GENERATED, never edited,
// and `--check` (run in CI and by test/design-system-parity.test.js) fails on any drift.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, '..', '..');
const vendor = join(here, '..', 'app', 'vendor');

const HEADER = '/* GENERATED by clients/scripts/sync-design-system.mjs from frontend/. Do not edit. */\n';

export function expected() {
  const icons = JSON.parse(readFileSync(join(repo, 'frontend/icons/icon-paths.json'), 'utf8'));
  return {
    'tokens.css': readFileSync(join(repo, 'frontend/design-system/tokens.css'), 'utf8'),
    'components.css': readFileSync(join(repo, 'frontend/design-system/components.css'), 'utf8'),
    // An ES module, because JSON import attributes are not available in every WebView the shells run in.
    'icon-paths.js': `${HEADER}export default ${JSON.stringify(icons)};\n`,
    '../brand/aiol-logo.svg': readFileSync(join(repo, 'frontend/brand/aiol-logo.svg'), 'utf8'),
  };
}

const check = process.argv.includes('--check');
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  let drift = 0;
  for (const [name, content] of Object.entries(expected())) {
    const target = join(vendor, name);
    const current = existsSync(target) ? readFileSync(target, 'utf8') : null;
    if (current === content) continue;
    if (check) { console.error(`DRIFT: clients/app/vendor/${name}`); drift++; }
    else { writeFileSync(target, content); console.log(`wrote clients/app/vendor/${name}`); }
  }
  process.exit(drift ? 1 : 0);
}
